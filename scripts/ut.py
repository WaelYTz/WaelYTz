ADV = 6                                           # glyph advance in cells (5 wide + 1 gap)


def clean(s: str) -> str:
    """Keep only drawable characters (emoji etc. dropped, runs of spaces collapsed to one)."""
    s = s.replace("—", "-").replace("–", "-").replace("…", "...").replace("★", "*")
    s = "".join(ch if ch in _G else " " for ch in s)
    lead = len(s) - len(s.lstrip(" "))
    return " " * lead + " ".join(s.split()) if s.strip() else ""


def width(s: str, scale: float) -> float:
    return max(0, len(s) * ADV - 1) * scale


def text(s: str, x: float, y: float, scale: float = 3, fill: str = WHITE, anchor: str = "start", raw: bool = False,
         extra: str = "") -> str:
    """Pixel text; (x, y) is the top-left (or top-centre / top-right for anchor middle / end)."""
    s = s if raw else clean(s)
    if anchor == "middle":
        x -= width(s, scale) / 2
    elif anchor == "end":
        x -= width(s, scale)
    d = []
    for i, ch in enumerate(s):
        g = _G.get(ch)
        if not g:
            continue
        gx = x + i * ADV * scale
        for r, row in enumerate(g):
            c = 0
            while c < 5:
                if row[c] == "#":
                    c0 = c
                    while c < 5 and row[c] == "#":
                        c += 1
                    d.append(f"M{gx + c0 * scale:.2f},{y + r * scale:.2f}h{(c - c0) * scale:.2f}v{scale:.2f}h{-(c - c0) * scale:.2f}z")
                else:
                    c += 1
    return f'<path d="{"".join(d)}" fill="{fill}" {extra}/>' if d else ""


def sprite(rows: list[str], x: float, y: float, px: float, colors: dict[str, str]) -> str:
    """Pixel sprite: rows of characters, each mapped to a colour ('.' = transparent)."""
    by_col: dict[str, list[str]] = {}
    for r, row in enumerate(rows):
        c = 0
        while c < len(row):
            ch = row[c]
            if ch in colors:
                c0 = c
                while c < len(row) and row[c] == ch:
                    c += 1
                by_col.setdefault(colors[ch], []).append(f"M{x + c0 * px:.2f},{y + r * px:.2f}h{(c - c0) * px:.2f}v{px:.2f}h{-(c - c0) * px:.2f}z")
            else:
                c += 1
    return "".join(f'<path d="{"".join(v)}" fill="{k}"/>' for k, v in by_col.items())


def box(x: float, y: float, w: float, h: float, stroke: str = WHITE, sw: float = 5) -> str:
    return f'<rect x="{x + sw / 2}" y="{y + sw / 2}" width="{w - sw}" height="{h - sw}" fill="#000" stroke="{stroke}" stroke-width="{sw}"/>'


def soul(x: float, y: float, px: float = 3, extra: str = "") -> str:
    """Pixel SOUL (7x6) with its top-left at (x, y)."""
    return f'<g {extra}>{sprite(SOUL_PIX, x, y, px, {"#": RED})}</g>'


def svg(w: int, h: int, body: str, label: str, style: str = "") -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" '
            f'aria-label="{label}" shape-rendering="crispEdges"><style>{style}</style><rect width="{w}" height="{h}" fill="#000"/>{body}</svg>')


