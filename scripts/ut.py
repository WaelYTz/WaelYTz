def typewriter(s: str, x: float, y: float, scale: float, start: float, dur: float, per: float = 0.05, fill: str = WHITE,
               cid: str = "tw") -> str:
    """Pixel text revealed one character at a time (SMIL, loops every dur seconds)."""
    s = clean(s) if not s.startswith("  ") else "  " + clean(s)
    n = len(s); full = width(s, scale) + scale
    ts, vs = [0.0], ["0"]
    for k in range(1, n + 1):
        ts.append(min(dur, start + k * per)); vs.append(f"{min(full, k * ADV * scale):.1f}")
    ts.append(dur); vs.append(f"{full:.1f}")
    kt = ";".join(f"{t / dur:.4f}" for t in ts)
    return (f'<clipPath id="{cid}"><rect x="{x}" y="{y - 2}" width="{full:.1f}" height="{8 * scale + 4}">'
            f'<animate attributeName="width" values="{";".join(vs)}" keyTimes="{kt}" dur="{dur}s" calcMode="discrete" repeatCount="indefinite"/>'
            f'</rect></clipPath><g clip-path="url(#{cid})">{text(s, x, y, scale, fill, raw=True)}</g>')
